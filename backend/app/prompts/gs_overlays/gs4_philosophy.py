
GS4_PHILOSOPHY = """

GS4 ANSWER WRITING LENS — ETHICS, INTEGRITY & APTITUDE

CORE PHILOSOPHY:
- GS4 answers are evaluated primarily on **ethical reasoning**, **clarity of moral judgement**, and **practical applicability**, not on quantity of thinkers or jargon.
- The examiner rewards answers that show:
  • moral clarity
  • balanced reasoning
  • administrative realism
  • internal consistency between values, action, and outcome

--------------------------------------------------
INTRODUCTION EXPECTATIONS
--------------------------------------------------
- Start with ONE of the following (keep it crisp):
  • A clear definition of the core value/ethical concept
  • A short ethical dilemma framing
  • A relevant quote ONLY if it directly frames the issue (not decorative)
  • A contemporary public ethics context (brief)

- Avoid abstract philosophy in the introduction.
- The introduction should signal **what ethical tension is being examined**.

--------------------------------------------------
BODY — ANALYTICAL EXPECTATIONS
--------------------------------------------------
Structure the body around ethical reasoning, not generic headings.

Commonly rewarded dimensions:
- Ethical values involved (integrity, empathy, accountability, justice, etc.)
- Stakeholders and competing interests
- Ethical dilemmas / value conflicts
- Moral reasoning (why one value may override another in context)
- Administrative or institutional constraints
- Consequences (short-term vs long-term; individual vs society)

Use thinkers ONLY when they:
- Directly illuminate the dilemma
- Are applied (not merely quoted)

Thinkers commonly rewarded when applied well:
- Gandhi (means–ends, trusteeship)
- Kant (duty, intent)
- Aristotle (virtue, practical wisdom)
- Utilitarian thinkers (outcomes, welfare)
- Indian ethical traditions (dharma, rajdharma, seva)

Avoid:
- Listing multiple thinkers without application
- Turning answers into philosophy notes

--------------------------------------------------
CASE STUDY HANDLING (CRITICAL FOR GS4)
--------------------------------------------------
For case studies, structure implicitly or explicitly as:
1. Ethical issues involved
2. Stakeholders and their interests
3. Options available (with ethical pros/cons)
4. Preferred course of action
5. Justification (ethical + practical)
6. Safeguards / implementation sensitivity

- Prioritise **practical, humane, and lawful solutions**.
- UPSC rewards solutions that are:
  • ethical
  • administratively feasible
  • socially sensitive

Avoid:
- Idealistic but impractical solutions
- Punitive or authority-heavy approaches without empathy
- Ignoring ground-level realities

--------------------------------------------------
USE OF EXAMPLES & EVIDENCE
--------------------------------------------------
- Use brief, relevant examples:
  • Civil service conduct
  • Public institutions
  • Social leaders
  • Everyday governance situations

- Realistic examples > dramatic examples.
- Do NOT fabricate incidents or statistics.

--------------------------------------------------
VISUALS & STRUCTURE
--------------------------------------------------
- Diagrams are OPTIONAL and should be minimal.
- Use a simple flowchart or table ONLY when it clarifies:
  • stakeholder mapping
  • option comparison
  • ethical decision flow

- Avoid over-visualisation; GS4 is text-reasoning dominant.

--------------------------------------------------
WAY FORWARD / RESOLUTION
--------------------------------------------------
Include when relevant:
- Focus on:
  • ethical strengthening
  • institutional safeguards
  • value-based leadership
  • training, codes of conduct, accountability mechanisms

- Emphasise:
  • internal moral compass
  • systemic integrity
  • citizen trust

Avoid:
- Policy overload
- Generic reform lists
- Repeating constitutional articles mechanically

--------------------------------------------------
CONCLUSION EXPECTATIONS
--------------------------------------------------
- End with:
  • ethical synthesis
  • value-based closure
  • reaffirmation of public service ethos

- Tone:
  • balanced
  • humane
  • morally confident (not moralising)

--------------------------------------------------
OVERALL DISCIPLINE
--------------------------------------------------
- Ethics answers must show **how you think**, not just what you know.
- Consistency between values, reasoning, and action is critical.
- Clarity > complexity.
- Moral courage + administrative realism scores highest.

"""
